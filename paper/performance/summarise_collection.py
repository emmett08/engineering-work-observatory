#!/usr/bin/env python3
"""Summarise a successor collection without writing the retained results directory."""
import argparse
import csv
import io
import os
import pathlib
import statistics
import tempfile

from run_benchmarks import HEADER, QS, REPETITIONS, ROOT, SEEDS
from collection_protocol import TIMINGS, validate_row


def summarise(raw):
    """Return summaries of the complete declared protocol; do not perform I/O."""
    raw = [validate_row(row) for row in raw]
    expected = {(seed, rep, q) for seed in SEEDS for rep in range(REPETITIONS) for q in QS}
    keys = [(row["seed"], row["rep"], row["q"]) for row in raw]
    if len(keys) != len(expected) or set(keys) != expected:
        raise ValueError("Expected exactly one observation for each declared seed/rep/query key")
    rows = []
    for q in QS:
        group = [entry for entry in raw if entry["q"] == q]
        row = {"q": q, "pairs": len(group)}
        for field in TIMINGS:
            values = [entry[field] / 1e6 for entry in group]
            for name, fn in (("median", statistics.median), ("min", min), ("max", max)):
                row[f"{field[:-3]}_{name}_ms"] = fn(values)
        baseline = row["scan_median_ms"]
        candidate = row["index_total_median_ms"]
        if baseline <= 0 or candidate <= 0:
            raise ValueError("Batch times must be positive")
        row["absolute_reduction_ms"] = baseline - candidate
        row["relative_reduction_percent"] = 100 * (baseline - candidate) / baseline
        row["speedup_ratio_of_medians"] = baseline / candidate
        paired = [100 * (entry["scan_ns"] - entry["index_total_ns"])
                  / entry["scan_ns"] for entry in group]
        row["paired_reduction_min_percent"] = min(paired)
        row["paired_reduction_max_percent"] = max(paired)
        rows.append(row)
    return rows


def replace_output(path, contents):
    """Replace the directory entry, preserving any existing symlink/hard-link target."""
    temporary = None
    try:
        with tempfile.NamedTemporaryFile(mode="w", encoding="utf-8", newline="",
                                         dir=path.parent, prefix=f".{path.name}.",
                                         delete=False) as stream:
            temporary = pathlib.Path(stream.name)
            stream.write(contents)
        os.replace(temporary, path)
    finally:
        if temporary is not None:
            temporary.unlink(missing_ok=True)


def write_summary(directory):
    directory = pathlib.Path(directory).resolve()
    retained = (ROOT / "results").resolve()
    if directory == retained or retained in directory.parents:
        raise ValueError("The retained results use the frozen summarise.py; choose a new collection")
    with (directory / "raw.csv").open() as stream:
        reader = csv.DictReader(stream)
        if reader.fieldnames != HEADER:
            raise ValueError("Unexpected benchmark result header")
        rows = summarise(list(reader))
    stream = io.StringIO(newline="")
    writer = csv.DictWriter(stream, fieldnames=list(rows[0]))
    writer.writeheader()
    writer.writerows(rows)
    row_end = chr(92) * 2
    table = ["% Generated by performance/summarise_collection.py; times in milliseconds.",
             "\\begin{tabular}{rrrrrr}", "\\toprule",
             "$q$ & Scan & Build & Query & Indexed total & Reduction " + row_end, "\\midrule"]
    for row in rows:
        table.append(f"{row['q']} & {row['scan_median_ms']:.3f} & {row['index_build_median_ms']:.3f} & {row['index_query_median_ms']:.3f} & {row['index_total_median_ms']:.3f} & {row['relative_reduction_percent']:.1f}\\% " + row_end)
    table += ["\\bottomrule", "\\end{tabular}", ""]
    replace_output(directory / "summary.csv", stream.getvalue())
    replace_output(directory / "table.tex", "\n".join(table))
    return rows


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("directory", type=pathlib.Path, help="successor collection directory")
    args = parser.parse_args()
    for row in write_summary(args.directory):
        print(f"q={row['q']:4d} scan={row['scan_median_ms']:.3f} ms, indexed={row['index_total_median_ms']:.3f} ms, reduction={row['relative_reduction_percent']:.1f}%")


if __name__ == "__main__":
    main()
