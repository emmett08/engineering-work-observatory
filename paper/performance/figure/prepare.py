#!/usr/bin/env python3
"""Validate retained machine timings and derive figure values (standard library only)."""
from __future__ import annotations

import argparse
import csv
import hashlib
import json
import math
import statistics
from collections import defaultdict
from pathlib import Path


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--raw", type=Path, default=Path(__file__).parents[1] / "results/raw.csv")
    parser.add_argument("--output", type=Path, default=Path(__file__).parent)
    args = parser.parse_args()
    rows = list(csv.DictReader(args.raw.open(newline="")))
    required = {"seed", "rep", "q", "first", "accepted_count", "labour_count", "delta_hours", "scan_ns", "index_build_ns",
                "index_query_ns", "index_drop_ns", "index_total_ns", "checksum"}
    if not rows or not required <= rows[0].keys():
        raise ValueError("The retained CSV is empty or lacks required timing fields")
    seen = set()
    grouped = defaultdict(list)
    for row in rows:
        for name in required - {"first"}:
            row[name] = int(row[name])
        key = row["seed"], row["rep"], row["q"]
        if key in seen:
            raise ValueError(f"Duplicate paired repetition: {key}")
        seen.add(key)
        if (row["accepted_count"], row["labour_count"], row["delta_hours"]) != (100000, 400000, 720):
            raise ValueError(f"Unexpected fixture size or fixed follow-up duration: {key}")
        if row["first"] not in {"scan", "index"}:
            raise ValueError(f"Unknown method order: {key}")
        if any(row[name] <= 0 for name in ("scan_ns", "index_build_ns", "index_query_ns", "index_total_ns")):
            raise ValueError(f"Nonpositive elapsed time: {key}")
        if row["index_total_ns"] < row["index_build_ns"] + row["index_query_ns"] + row["index_drop_ns"]:
            raise ValueError(f"Indexed total omits a timed component: {key}")
        grouped[row["q"]].append(row)
    if set(grouped) != {1, 10, 100, 1000}:
        raise ValueError("Expected exactly q=1,10,100,1000; missing observations are not zero-filled")
    pairs = {(row["seed"], row["rep"]) for row in rows}
    if any({(r["seed"], r["rep"]) for r in group} != pairs for group in grouped.values()):
        raise ValueError("The tested query counts do not have the same seed/repetition set")
    if len(pairs) != 15 or len({r["seed"] for r in rows}) != 3:
        raise ValueError("This registered figure expects 3 seeds x 5 paired repetitions")
    if any(sum(seed == s for s, rep in pairs) != 5 for seed in {s for s, rep in pairs}):
        raise ValueError("Each seed must have exactly five paired repetitions")

    stats = []
    for q, group in sorted(grouped.items()):
        item = {"q": q, "pairs": len(group)}
        for name, values in (
            ("scan", [r["scan_ns"] / 1e6 for r in group]),
            ("indexed", [r["index_total_ns"] / 1e6 for r in group]),
            ("build", [r["index_build_ns"] / 1e6 for r in group]),
            ("ratio", [r["scan_ns"] / r["index_total_ns"] for r in group]),
        ):
            median = statistics.median(values)
            item.update({name: median, name + "_min": min(values), name + "_max": max(values),
                         name + "_minus": median - min(values), name + "_plus": max(values) - median})
            assert item[name + "_min"] <= item[name] <= item[name + "_max"]
        stats.append(item)
    args.output.mkdir(parents=True, exist_ok=True)
    with (args.output / "horizon-data.csv").open("w", newline="") as out:
        writer = csv.DictWriter(out, fieldnames=list(stats[0]))
        writer.writeheader()
        writer.writerows(stats)

    unanimous_wins = [s["q"] for s in stats if s["ratio_min"] > 1]
    unanimous_losses = [s["q"] for s in stats if s["ratio_max"] < 1]
    if not unanimous_wins or 1 not in unanimous_losses:
        raise ValueError("Observed results do not support the proposed finding title; revise the account")
    first_win = min(unanimous_wins)
    timing_min = min(s[k] for s in stats for k in ("scan_min", "indexed_min")) * .7
    timing_max = max(s[k] for s in stats for k in ("scan_max", "indexed_max")) * 1.3
    timing_ticks = [10 ** p for p in range(math.ceil(math.log10(timing_min)), math.floor(math.log10(timing_max)) + 1)]
    ratio_min = 10 ** math.floor(math.log10(min(s["ratio_min"] for s in stats) * .7))
    ratio_max = 10 ** math.ceil(math.log10(max(s["ratio_max"] for s in stats) * 1.1))
    ratio_ticks = [10 ** p for p in range(round(math.log10(ratio_min)), round(math.log10(ratio_max)) + 1)]
    label_text = (
        "% Generated by performance/figure/prepare.py from retained raw timings.\n"
        f"\\def\\HorizonFirstWin{{{first_win:,}}}\n"
        f"\\def\\HorizonFinding{{Indexing is faster in all {first_win:,}-query runs}}\n"
        f"\\def\\HorizonOneRatio{{{stats[0]['ratio']:.2f}}}\n"
        f"\\def\\HorizonManyRatio{{{stats[-1]['ratio']:.1f}}}\n"
        f"\\def\\HorizonYmin{{{timing_min:g}}}\n"
        f"\\def\\HorizonYmax{{{timing_max:g}}}\n"
        f"\\def\\HorizonYticks{{{','.join(f'{v:g}' for v in timing_ticks)}}}\n"
        f"\\def\\HorizonRmin{{{ratio_min:g}}}\n"
        f"\\def\\HorizonRmax{{{ratio_max:g}}}\n"
        f"\\def\\HorizonRticks{{{','.join(f'{v:g}' for v in ratio_ticks)}}}\n"
        f"\\def\\HorizonScanLast{{{stats[-1]['scan']:.9g}}}\n"
        f"\\def\\HorizonIndexedLast{{{stats[-1]['indexed']:.9g}}}\n"
    )
    (args.output / "horizon-labels.tex").write_text(label_text)
    caption = (
        "Observed elapsed times for repeated cohort-horizon queries on generated arrays "
        "of 100,000 accepted-output records and 400,000 labour increments. "
        "Markers are medians. Whiskers show the minimum and maximum across 15 paired "
        "runs (three seeds, five fresh-process repetitions per seed). They are not confidence intervals. "
        "Indexed totals include construction, queries and disposal. All one-query "
        f"pairs favoured scanning and all {first_win:,}-query pairs favoured indexing. "
        "Ten-query pairs varied in direction. "
        "Only four query counts were timed, so the connecting lines do not locate break-even. "
        "This result is confined to the generated workload and execution environment "
        "and does not estimate human labour or an effect of an AI intervention.\n"
    )
    figure_dir = args.output.parents[1] / "figures"
    figure_dir.mkdir(parents=True, exist_ok=True)
    (figure_dir / "horizon-performance.caption.tex").write_text(caption)
    result = {
        "raw_sha256": digest(args.raw),
        "raw_rows": len(rows), "pairs_per_query_count": len(pairs),
        "seeds": sorted({r["seed"] for r in rows}),
        "query_counts": sorted(grouped),
        "aggregation": "Median; whiskers are observed min-max over the 15 paired repetitions, not confidence intervals.",
        "ratio": "Median of within-pair scan_ns/index_total_ns, not ratio of marginal medians.",
        "included_cost": "index_total_ns independently measures build through disposal and is at least the sum of build, query and drop sub-timings in every retained row.",
        "missingness": "No missing or duplicate seed/repetition/query-count records; no exclusions or imputation.",
        "unanimous_faster_query_counts": unanimous_wins,
        "unanimous_slower_query_counts": unanimous_losses,
        "crossing_limit": "Only the four declared query counts were timed; no exact break-even query count is estimated.",
        "scope": "Observed machine elapsed times on generated accepted-output event and labour-increment arrays, without a full task roster or task-to-increment associations; no observed human labour or policy effect.",
        "summary": stats,
    }
    (args.output / "calculation-checks.json").write_text(json.dumps(result, indent=2) + "\n")
    paper = args.output.parents[1]
    spec_path = paper / "horizon-performance.spec.json"
    if spec_path.exists():
        spec = json.loads(spec_path.read_text())
        spec["purpose"]["claim"] = (
            f"All 15 observed pairs favoured scanning at q=1 and indexing at q={first_win}, "
            "the first sampled count with a unanimous indexed advantage; exact break-even is unmeasured."
        )
        for item in spec["inputs"]:
            if "path" in item:
                item["sha256"] = digest(paper / item["path"])
        for item in spec["encodings"]:
            if item["id"] == "time-position":
                item["scale_or_mapping"]["domain"] = [timing_min, timing_max]
        spec_path.write_text(json.dumps(spec, indent=2) + "\n")
    print(json.dumps({k: result[k] for k in ("raw_rows", "pairs_per_query_count", "unanimous_faster_query_counts", "unanimous_slower_query_counts")}, indent=2))


if __name__ == "__main__":
    main()
