#!/usr/bin/env python3
"""Derive medians, ranges and a LaTeX table from all recorded paired observations."""
import csv
import pathlib
import statistics

ROOT = pathlib.Path(__file__).resolve().parent
RESULTS = ROOT / "results"
TIMINGS = ("scan_ns", "index_build_ns", "index_query_ns", "index_drop_ns", "index_total_ns")


def main():
    with (RESULTS / "raw.csv").open() as f:
        raw = list(csv.DictReader(f))
    assert len(raw) == 60, f"Expected 60 paired processes, got {len(raw)}"
    rows = []
    for q in (1, 10, 100, 1000):
        group = [row for row in raw if int(row["q"]) == q]
        assert len(group) == 15
        assert {(int(r["seed"]), int(r["rep"])) for r in group} == {(s, r) for s in (17, 41, 93) for r in range(5)}
        row = {"q": q, "pairs": len(group)}
        for field in TIMINGS:
            values = [int(r[field]) / 1e6 for r in group]
            for name, fn in (("median", statistics.median), ("min", min), ("max", max)):
                row[f"{field[:-3]}_{name}_ms"] = fn(values)
        b = row["scan_median_ms"]
        c = row["index_total_median_ms"]
        row["absolute_reduction_ms"] = b - c
        row["relative_reduction_percent"] = 100 * (b - c) / b
        row["speedup_ratio_of_medians"] = b / c
        row["paired_reduction_min_percent"] = min(100 * (int(r["scan_ns"]) - int(r["index_total_ns"])) / int(r["scan_ns"]) for r in group)
        row["paired_reduction_max_percent"] = max(100 * (int(r["scan_ns"]) - int(r["index_total_ns"])) / int(r["scan_ns"]) for r in group)
        rows.append(row)
    with (RESULTS / "summary.csv").open("w", newline="") as f:
        writer = csv.DictWriter(f, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)
    row_end = chr(92) * 2
    table = ["% Generated by performance/summarise.py; all times in milliseconds.",
             "\\begin{tabular}{rrrrrr}", "\\toprule",
             "$q$ & Scan & Build & Query & Indexed total & Reduction " + row_end, "\\midrule"]
    for row in rows:
        table.append(f"{row['q']} & {row['scan_median_ms']:.3f} & {row['index_build_median_ms']:.3f} & {row['index_query_median_ms']:.3f} & {row['index_total_median_ms']:.3f} & {row['relative_reduction_percent']:.1f}\\% " + row_end)
    table += ["\\bottomrule", "\\end{tabular}", ""]
    (RESULTS / "table.tex").write_text("\n".join(table))
    for row in rows:
        print(f"q={row['q']:4d} scan={row['scan_median_ms']:.3f} ms, indexed={row['index_total_median_ms']:.3f} ms, reduction={row['relative_reduction_percent']:.1f}%")


if __name__ == "__main__":
    main()
